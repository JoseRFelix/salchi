// Generates src/themesGenerated.ts: static metadata + lazy loaders for the
// bundled Shiki / VS Code themes. Run from apps/web after bumping
// @shikijs/themes:
//
//   node scripts/generate-theme-registry.mjs
//
// We vendor a static registry (rather than importing shiki's `bundledThemesInfo`
// at runtime) so the picker can list/group all themes without pulling the full
// `shiki` package — `@shikijs/themes` only exports `themeNames`.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { themeNames } from "@shikijs/themes";

const rows = [];
for (const id of [...themeNames].sort()) {
  const mod = await import(`@shikijs/themes/${id}`);
  const theme = mod.default?.default ?? mod.default;
  rows.push({
    id,
    label: theme.displayName ?? theme.name ?? id,
    type: theme.type === "light" ? "light" : "dark",
  });
}

const header = `// @generated by scripts/generate-theme-registry.mjs — do not edit by hand.
// Static metadata + lazy loaders for the bundled Shiki / VS Code themes.
// Regenerate after bumping @shikijs/themes.
import type { ThemeRegistration } from "@pierre/diffs";

import type { ResolvedThemeType } from "./themeMapping";

export interface BundledThemeInfo {
  readonly id: string;
  readonly label: string;
  readonly type: ResolvedThemeType;
}

`;

const info = `export const BUNDLED_THEME_INFO: ReadonlyArray<BundledThemeInfo> = [
${rows
  .map(
    (r) =>
      `  { id: ${JSON.stringify(r.id)}, label: ${JSON.stringify(r.label)}, type: ${JSON.stringify(
        r.type,
      )} },`,
  )
  .join("\n")}
];

`;

const loaders = `export const BUNDLED_THEME_LOADERS: Readonly<
  Record<string, () => Promise<{ default: ThemeRegistration }>>
> = {
${rows.map((r) => `  ${JSON.stringify(r.id)}: () => import(${JSON.stringify(`@shikijs/themes/${r.id}`)}),`).join("\n")}
};
`;

const outPath = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "themesGenerated.ts");
writeFileSync(outPath, header + info + loaders);
console.log(`Wrote ${outPath} with ${rows.length} themes`);
